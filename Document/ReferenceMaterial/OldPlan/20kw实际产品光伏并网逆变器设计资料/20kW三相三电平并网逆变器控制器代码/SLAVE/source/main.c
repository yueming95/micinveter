/**********************************************************************
* PRD_TimeBase2ms function
* Post SEM_StateSwitch_2msPRD when periodic timerBase of 2ms is ready,
* used for state switching.
**********************************************************************/
void PRD_F_TimeBase2ms(void)
{
	SEM_post(&SEM_StateSwitch_2msPRD);
}

/**********************************************************************
* PRD_TimeBase500ms function
* Post SEM_LINa_500msPRD when periodic timerBase of 500ms is ready,
* used for LINa.
**********************************************************************/

void PRD_F_TimeBase500ms(void)
{
	static Uint16 ExitSCiFaultCnt = 0;
	if(0 == s_SysFaultMessage.bit.SciCommLose)
	{
		if(g_SCICommCnt > 40)
		{
			s_SysFaultMessage.bit.SciCommLose = 1;
		}
	}
	else
	{
		if(g_SCICommCnt < 4)
		{
			ExitSCiFaultCnt++;
			if(ExitSCiFaultCnt > 12)
			{
				s_SysFaultMessage.bit.SciCommLose = 0;
				ExitSCiFaultCnt = 0;
			}
		}
	}
	g_SCICommCnt++;
//	AdcRegs.ADCSOCFRC1.bit.SOC15 = 1;	// for test
}

/**********************************************************************
* SPIb task function
**********************************************************************/
void TSK_F_SPIb(void)
{
	while(1)
	{
		SEM_pend(&SEM_SPIb, SYS_FOREVER);

		SetSlaveValue();
		SpiSlaveUpdateData();
		ConsistentCheck();
	}
}

