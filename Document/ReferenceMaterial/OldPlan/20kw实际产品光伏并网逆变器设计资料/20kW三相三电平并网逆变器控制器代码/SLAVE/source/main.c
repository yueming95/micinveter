	InitPeripheralClocks();

// Step 5. User specific code:
	memcpy(&RamfuncsRunStart, &RamfuncsLoadStart, (Uint32)&RamfuncsLoadSize);
	InitFlash();
	memcpy(&ControlLoopInRAMRunStart, &ControlLoopInRAMLoadStart, (Uint32)&ControlLoopInRAMLoadSize);

