	Adc_PowerOn();
	AdcOffsetSelfCal(); 
	InitAdc();
	InitEPwm();
	SysParamDefault(); 
	InitSpi();//
	InitSci();
	InitI2C();

//	EINT;	// Enable Global interrupt INTM
